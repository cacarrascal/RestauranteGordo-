-- =====================================================
-- POLÍTICAS RLS (Row Level Security)
-- =====================================================

-- Habilitar RLS
ALTER TABLE public.mesas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.horarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.administradores ENABLE ROW LEVEL SECURITY;

-- Políticas para administradores - solo lectura pública para login
CREATE POLICY "Anyone can read administradores" ON public.administradores FOR SELECT USING (true);

-- Políticas para mesas - everyone can read, everyone can write
CREATE POLICY "Anyone can read mesas" ON public.mesas FOR SELECT USING (true);
CREATE POLICY "Anyone can insert mesas" ON public.mesas FOR INSERT WITH CHECK (true);
CREATE POLICY "Anyone can update mesas" ON public.mesas FOR UPDATE USING (true);
CREATE POLICY "Anyone can delete mesas" ON public.mesas FOR DELETE USING (true);

-- Políticas para reservas - everyone can read, everyone can write
CREATE POLICY "Anyone can read reservas" ON public.reservas FOR SELECT USING (true);
CREATE POLICY "Anyone can insert reservas" ON public.reservas FOR INSERT WITH CHECK (true);
CREATE POLICY "Anyone can update reservas" ON public.reservas FOR UPDATE USING (true);
CREATE POLICY "Anyone can delete reservas" ON public.reservas FOR DELETE USING (true);

-- Políticas para horarios - everyone can read, everyone can write
CREATE POLICY "Anyone can read horarios" ON public.horarios FOR SELECT USING (true);
CREATE POLICY "Anyone can insert horarios" ON public.horarios FOR INSERT WITH CHECK (true);
CREATE POLICY "Anyone can update horarios" ON public.horarios FOR UPDATE USING (true);
CREATE POLICY "Anyone can delete horarios" ON public.horarios FOR DELETE USING (true);

-- =====================================================
-- ÍNDICES PARA MEJOR RENDIMIENTO
-- =====================================================
CREATE INDEX idx_mesas_numero ON public.mesas(numero);
CREATE INDEX idx_reservas_fecha ON public.reservas(fecha);
CREATE INDEX idx_reservas_mesa_fecha ON public.reservas(mesa_id, fecha);
CREATE INDEX idx_horarios_dia ON public.horarios(dia_semana);

