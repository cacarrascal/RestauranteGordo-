-- =====================================================
-- BASE DE DATOS - THE GORDO RESTAURANT RESERVAS
-- =====================================================

-- =====================================================
-- TABLA: ADMINISTRADORES
-- =====================================================
CREATE TABLE IF NOT EXISTS public.administradores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  nombre TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- =====================================================
-- TABLA: MESAS
-- =====================================================
CREATE TABLE IF NOT EXISTS public.mesas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero INTEGER NOT NULL UNIQUE,
  capacidad INTEGER NOT NULL CHECK (capacidad >= 1 AND capacidad <= 20),
  ubicacion TEXT,
  estado TEXT NOT NULL DEFAULT 'disponible' CHECK (estado IN ('disponible', 'ocupada', 'bloqueada')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- =====================================================
-- TABLA: RESERVAS
-- =====================================================
CREATE TABLE IF NOT EXISTS public.reservas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mesa_id BIGINT NOT NULL REFERENCES public.mesas(id) ON DELETE CASCADE,
  cliente_nombre TEXT NOT NULL,
  cliente_tel TEXT NOT NULL,
  cliente_email TEXT NOT NULL,
  fecha DATE NOT NULL,
  hora TEXT NOT NULL,
  num_personas INTEGER NOT NULL CHECK (num_personas >= 1 AND num_personas <= 20),
  estado TEXT NOT NULL DEFAULT 'confirmada' CHECK (estado IN ('confirmada', 'cancelada')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- =====================================================
-- TABLA: HORARIOS
-- =====================================================
CREATE TABLE IF NOT EXISTS public.horarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dia_semana INTEGER NOT NULL CHECK (dia_semana >= 0 AND dia_semana <= 6),
  hora_inicio TEXT NOT NULL,
  hora_fin TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

